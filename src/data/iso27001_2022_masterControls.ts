// Helper functions for SoA calculations
export function getSoAThemeSummary(controls: ControlItem[]) {
  const themes: ISO27001Theme[] = ['Organizational', 'People', 'Physical', 'Technological'];
  return themes.map(theme => {
    const themeControls = controls.filter(c => c.category === theme);
    const applicable = themeControls.filter(c => c.applicable);
    const excluded = themeControls.filter(c => !c.applicable);
    const implemented = themeControls.filter(
      c => c.applicable && (c.implementationStatus === 'Implemented' || c.implementationStatus === 'Audited' || c.implementationStatus === 'Monitored')
    );
    const inProgress = themeControls.filter(c => c.applicable && c.implementationStatus === 'In Progress');
    const notStarted = themeControls.filter(c => c.applicable && c.implementationStatus === 'Not Started');
    const rate = applicable.length > 0 ? Math.round((implemented.length / applicable.length) * 100) : 0;

    return {
      theme,
      total: themeControls.length,
      applicableCount: applicable.length,
      excludedCount: excluded.length,
      implementedCount: implemented.length,
      inProgressCount: inProgress.length,
      notStartedCount: notStarted.length,
      implementationRate: rate
    };
  });
}

