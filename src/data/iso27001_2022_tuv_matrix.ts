/**
 * Returns statistics for the full 93 controls matrix
 */
export function getTUVMatrixSummary() {
  const total = ISO27001_2022_TUV_MATRIX.length; // 93
  const org = ISO27001_2022_TUV_MATRIX.filter(c => c.theme === 'Organizational'); // 37
  const people = ISO27001_2022_TUV_MATRIX.filter(c => c.theme === 'People'); // 8
  const physical = ISO27001_2022_TUV_MATRIX.filter(c => c.theme === 'Physical'); // 14
  const tech = ISO27001_2022_TUV_MATRIX.filter(c => c.theme === 'Technological'); // 34
  const new2022 = ISO27001_2022_TUV_MATRIX.filter(c => c.isNewIn2022); // 11
  const applicable = ISO27001_2022_TUV_MATRIX.filter(c => c.defaultApplicable);
  const excluded = ISO27001_2022_TUV_MATRIX.filter(c => !c.defaultApplicable);

  return {
    total,
    orgCount: org.length,
    peopleCount: people.length,
    physicalCount: physical.length,
    techCount: tech.length,
    new2022Count: new2022.length,
    applicableCount: applicable.length,
    excludedCount: excluded.length
  };
}
